// Package yamlconf generates type-safe config loaders from a simple YAML file
// and a user-defined Go struct. It is meant to be driven by go generate.
//
// YAML values take one of these forms:
//
//	port: ${APP_PORT:8080}   # env APP_PORT, fallback 8080
//	host: ${APP_HOST}        # env APP_HOST, no fallback (nil if unset)
//	name: "my-service"       # literal value, no env lookup
//	retries: 5               # literal value, no env lookup
//
// Every scalar/struct field must be a pointer; slices and maps may be used
// directly ([]*T, map[string]*T) or behind a pointer (*[]*T). A value ends up
// nil when neither the env var nor a fallback/literal provides one:
//
//   - YAML mappings bind to *Struct or map[string]*T,
//   - YAML sequences bind to []*T (T may itself be a struct, slice or map),
//   - containers and structs stay nil when none of their children got a value
//     (a nil element inside a non-nil slice keeps its index),
//   - anchors (&a), aliases (*a) and merge keys (<<: *a) are supported.
//
// Env vars are resolved at runtime by the generated code; fallbacks and
// literals are validated against the field type at generate time and baked
// in as Go constants.
package yamlconf

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/parser"
	"go/token"
	"math"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"strconv"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

// Options configures Generate.
type Options struct {
	// Dir is the package directory holding the target struct. Defaults to ".".
	Dir string
	// Type is the root struct type name. Required.
	Type string
	// YAMLFile is the YAML path, relative to Dir unless absolute. Required.
	YAMLFile string
	// Output is the generated file name; it is excluded when parsing Dir.
	Output string
	// Func is the loader function name. Defaults to "Load" + Type.
	Func string
	// Prefix is a dotted path into the YAML (e.g. "services.billing.db")
	// whose mapping binds to Type. Numeric segments index into sequences.
	// Empty means the document root.
	Prefix string
}

// Generate returns gofmt'ed Go source for the loader.
func Generate(opts Options) ([]byte, error) {
	if opts.Type == "" {
		return nil, errors.New("yamlconf: Type is required")
	}
	if opts.YAMLFile == "" {
		return nil, errors.New("yamlconf: YAMLFile is required")
	}
	if opts.Dir == "" {
		opts.Dir = "."
	}
	if opts.Func == "" {
		opts.Func = "Load" + opts.Type
	}

	pkgName, types, err := parsePackage(opts.Dir, filepath.Base(opts.Output))
	if err != nil {
		return nil, err
	}
	rootExpr, ok := types[opts.Type]
	if !ok {
		return nil, fmt.Errorf("yamlconf: type %s not found in %s", opts.Type, opts.Dir)
	}
	rootStruct, ok := rootExpr.(*ast.StructType)
	if !ok {
		return nil, fmt.Errorf("yamlconf: type %s is not a struct", opts.Type)
	}

	yamlPath := opts.YAMLFile
	if !filepath.IsAbs(yamlPath) {
		yamlPath = filepath.Join(opts.Dir, yamlPath)
	}
	root, err := readYAML(yamlPath)
	if err != nil {
		return nil, err
	}

	root, err = lookupPrefix(root, opts.Prefix)
	if err != nil {
		return nil, fmt.Errorf("yamlconf: %s: %w", filepath.Base(opts.YAMLFile), err)
	}

	g := &gen{types: types}
	var body bytes.Buffer
	if root != nil {
		if err := g.structFields(&body, rootStruct, root, "c", "", opts.Prefix); err != nil {
			return nil, err
		}
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by yamlconf from %s. DO NOT EDIT.\n\n", filepath.Base(opts.YAMLFile))
	fmt.Fprintf(&out, "package %s\n\n", pkgName)
	out.WriteString("import (\n")
	if g.useFmt {
		out.WriteString("\t\"fmt\"\n")
	}
	out.WriteString("\t\"os\"\n")
	if g.useStrconv {
		out.WriteString("\t\"strconv\"\n")
	}
	if g.useTime {
		out.WriteString("\t\"time\"\n")
	}
	out.WriteString(")\n\n")

	fmt.Fprintf(&out, "// %s builds a %s from the process environment.\n", opts.Func, opts.Type)
	fmt.Fprintf(&out, "func %s() (*%s, error) {\n\treturn %sWith(os.LookupEnv)\n}\n\n", opts.Func, opts.Type, opts.Func)
	fmt.Fprintf(&out, "// %sWith builds a %s using lookup to resolve env vars.\n", opts.Func, opts.Type)
	fmt.Fprintf(&out, "// An env var that is unset or empty falls back to the YAML fallback, if any.\n")
	lookupParam := "lookup"
	if !g.usedLookup {
		lookupParam = "_"
	}
	fmt.Fprintf(&out, "func %sWith(%s func(string) (string, bool)) (*%s, error) {\n", opts.Func, lookupParam, opts.Type)
	fmt.Fprintf(&out, "\tc := &%s{}\n", opts.Type)
	out.Write(body.Bytes())
	out.WriteString("\treturn c, nil\n}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("yamlconf: formatting generated code: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

// ---------- marker discovery ----------

// Directive is the marker comment placed directly above a struct:
//
//	//yamlconf:generate config.yaml [func=LoadConfig] [out=config_yamlconf.go]
const Directive = "//yamlconf:generate"

// GeneratedSuffix is the default output file suffix; such files are ignored
// when parsing the package.
const GeneratedSuffix = "_yamlconf.go"

// Target is one struct marked with Directive.
type Target struct {
	Type     string
	YAMLFile string
	Func     string // empty means "Load" + Type
	Prefix   string // dotted YAML path the struct binds to; empty = root
	Output   string // defaults to lower(Type) + GeneratedSuffix
}

// Discover finds every struct in dir annotated with Directive.
func Discover(dir string) ([]Target, error) {
	if dir == "" {
		dir = "."
	}
	fset, _, files, err := parseFiles(dir, "", parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var targets []Target
	for _, f := range files {
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				args, found := findDirective(doc)
				if !found {
					continue
				}
				pos := fset.Position(ts.Pos())
				if _, ok := ts.Type.(*ast.StructType); !ok {
					return nil, fmt.Errorf("yamlconf: %s: %s marks %s, which is not a struct", pos, Directive, ts.Name.Name)
				}
				t, err := parseDirective(ts.Name.Name, args)
				if err != nil {
					return nil, fmt.Errorf("yamlconf: %s: %w", pos, err)
				}
				targets = append(targets, t)
			}
		}
	}
	return targets, nil
}

func findDirective(doc *ast.CommentGroup) (string, bool) {
	if doc == nil {
		return "", false
	}
	for _, c := range doc.List {
		if rest, ok := strings.CutPrefix(c.Text, Directive); ok && (rest == "" || rest[0] == ' ' || rest[0] == '\t') {
			return strings.TrimSpace(rest), true
		}
	}
	return "", false
}

func parseDirective(typeName, args string) (Target, error) {
	t := Target{Type: typeName}
	for _, f := range strings.Fields(args) {
		k, v, isKV := strings.Cut(f, "=")
		switch {
		case !isKV && t.YAMLFile == "":
			t.YAMLFile = f
		case !isKV:
			return t, fmt.Errorf("%s on %s: unexpected argument %q", Directive, typeName, f)
		case k == "yaml":
			t.YAMLFile = v
		case k == "func":
			t.Func = v
		case k == "out":
			t.Output = v
		case k == "prefix":
			t.Prefix = strings.Trim(v, ".")
		default:
			return t, fmt.Errorf("%s on %s: unknown option %q (want yaml=, func=, out=, prefix=)", Directive, typeName, k)
		}
	}
	if t.YAMLFile == "" {
		return t, fmt.Errorf("%s on %s: missing YAML file, e.g. %s config.yaml", Directive, typeName, Directive)
	}
	if t.Output == "" {
		t.Output = strings.ToLower(typeName) + GeneratedSuffix
	}
	return t, nil
}

// ---------- Go source parsing ----------

// parseFiles parses the package's non-test Go files in dir, honouring build
// constraints like the go tool does, in sorted order. Generated loaders
// (*_yamlconf.go) and the file named exclude are skipped.
func parseFiles(dir, exclude string, mode parser.Mode) (*token.FileSet, string, []*ast.File, error) {
	bp, err := build.ImportDir(dir, 0)
	if err != nil {
		return nil, "", nil, fmt.Errorf("yamlconf: loading package %s: %w", dir, err)
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range bp.GoFiles {
		if strings.HasSuffix(name, GeneratedSuffix) || name == exclude {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, mode|parser.SkipObjectResolution)
		if err != nil {
			return nil, "", nil, fmt.Errorf("yamlconf: parsing %s: %w", dir, err)
		}
		files = append(files, f)
	}
	return fset, bp.Name, files, nil
}

func parsePackage(dir, exclude string) (string, map[string]ast.Expr, error) {
	_, name, files, err := parseFiles(dir, exclude, 0)
	if err != nil {
		return "", nil, err
	}
	types := map[string]ast.Expr{}
	for _, f := range files {
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				types[ts.Name.Name] = ts.Type
			}
		}
	}
	return name, types, nil
}

type kind int

const (
	kString kind = iota
	kBool
	kInt
	kUint
	kFloat
	kDuration
)

type scalarType struct {
	kind   kind
	bits   int    // for strconv; 0 means platform int size
	goType string // type name used for conversions, e.g. "int", "LogLevel"
}

var basicTypes = map[string]scalarType{
	"string":  {kString, 0, "string"},
	"bool":    {kBool, 0, "bool"},
	"int":     {kInt, 0, "int"},
	"int8":    {kInt, 8, "int8"},
	"int16":   {kInt, 16, "int16"},
	"int32":   {kInt, 32, "int32"},
	"int64":   {kInt, 64, "int64"},
	"uint":    {kUint, 0, "uint"},
	"uint8":   {kUint, 8, "uint8"},
	"uint16":  {kUint, 16, "uint16"},
	"uint32":  {kUint, 32, "uint32"},
	"uint64":  {kUint, 64, "uint64"},
	"float32": {kFloat, 32, "float32"},
	"float64": {kFloat, 64, "float64"},
	"byte":    {kUint, 8, "byte"},
	"rune":    {kInt, 32, "rune"},
}

// resolve classifies the element type of a pointer field. Exactly one of the
// results is non-nil on success.
func (g *gen) resolve(e ast.Expr) (*scalarType, *ast.StructType, string, error) {
	return g.resolveDepth(e, 0)
}

func (g *gen) resolveDepth(e ast.Expr, depth int) (*scalarType, *ast.StructType, string, error) {
	if depth > 16 {
		return nil, nil, "", errors.New("type definition too deep")
	}
	switch t := e.(type) {
	case *ast.Ident:
		if bt, ok := basicTypes[t.Name]; ok {
			return &bt, nil, t.Name, nil
		}
		def, ok := g.types[t.Name]
		if !ok {
			return nil, nil, "", fmt.Errorf("unknown type %s", t.Name)
		}
		if st, ok := def.(*ast.StructType); ok {
			return nil, st, t.Name, nil
		}
		// Named type over a scalar, e.g. `type LogLevel string`.
		sc, st, _, err := g.resolveDepth(def, depth+1)
		if err != nil {
			return nil, nil, "", err
		}
		if st != nil {
			return nil, st, t.Name, nil
		}
		named := *sc
		named.goType = t.Name
		return &named, nil, t.Name, nil
	case *ast.SelectorExpr:
		if x, ok := t.X.(*ast.Ident); ok && x.Name == "time" && t.Sel.Name == "Duration" {
			return &scalarType{kind: kDuration, goType: "time.Duration"}, nil, "time.Duration", nil
		}
	case *ast.StructType:
		return nil, t, "", nil
	}
	return nil, nil, "", fmt.Errorf("unsupported type %s", exprString(e))
}

func exprString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + exprString(t.X)
	case *ast.SelectorExpr:
		return exprString(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		return "[]" + exprString(t.Elt)
	case *ast.MapType:
		return "map[" + exprString(t.Key) + "]" + exprString(t.Value)
	}
	return fmt.Sprintf("%T", e)
}

// ---------- YAML ----------

func readYAML(path string) (*yaml.Node, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("yamlconf: %w", err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("yamlconf: parsing %s: %w", path, err)
	}
	if len(doc.Content) == 0 {
		return nil, nil // empty file: everything nil
	}
	root := deref(doc.Content[0])
	if root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("yamlconf: %s: top level must be a mapping", path)
	}
	return root, nil
}

func deref(n *yaml.Node) *yaml.Node {
	for n.Kind == yaml.AliasNode && n.Alias != nil {
		n = n.Alias
	}
	return n
}

func isNull(n *yaml.Node) bool {
	return n.Kind == yaml.ScalarNode && n.Tag == "!!null"
}

// value is a parsed YAML scalar.
type value struct {
	env         string // env var name, "" for none
	fallback    string
	hasFallback bool
}

var refRe = regexp.MustCompile(`^\$\{([A-Za-z_][A-Za-z0-9_]*)?(?::(.*))?\}$`)

// parseValue interprets a scalar as ${ENV:fallback}, ${ENV}, ${:fallback}, or a literal.
// An empty fallback (`${ENV:}`) counts as no fallback.
func parseValue(n *yaml.Node) (value, error) {
	s := n.Value
	if m := refRe.FindStringSubmatch(s); m != nil {
		v := value{env: m[1], fallback: m[2], hasFallback: m[2] != ""}
		if v.env == "" && !v.hasFallback {
			return value{}, fmt.Errorf("empty reference %q", s)
		}
		return v, nil
	}
	if strings.HasPrefix(s, "${") {
		return value{}, fmt.Errorf("malformed reference %q, want ${ENV} or ${ENV:fallback}", s)
	}
	return value{fallback: s, hasFallback: true}, nil
}

// lookupPrefix walks a dotted path from root. It returns nil (all fields nil)
// when the path ends at a null value, and an error when a segment is missing.
func lookupPrefix(root *yaml.Node, prefix string) (*yaml.Node, error) {
	prefix = strings.Trim(prefix, ".")
	if prefix == "" {
		return root, nil
	}
	if root == nil {
		return nil, fmt.Errorf("prefix %q: YAML file is empty", prefix)
	}
	cur := root
	walked := ""
	for _, seg := range strings.Split(prefix, ".") {
		if seg == "" {
			return nil, fmt.Errorf("prefix %q: empty segment", prefix)
		}
		var next *yaml.Node
		switch cur.Kind {
		case yaml.MappingNode:
			kvs, err := pairs(cur, 0)
			if err != nil {
				return nil, fmt.Errorf("prefix %q at %s: %w", prefix, orRoot(walked), err)
			}
			for _, p := range kvs {
				if p.key.Value == seg {
					next = p.val
					break
				}
			}
		case yaml.SequenceNode:
			if i, err := strconv.Atoi(seg); err == nil && i >= 0 && i < len(cur.Content) {
				next = cur.Content[i]
			}
		default:
			return nil, fmt.Errorf("prefix %q: %s (line %d) is a scalar, cannot descend into %q", prefix, orRoot(walked), cur.Line, seg)
		}
		walked = joinPath(walked, seg)
		if next == nil {
			return nil, fmt.Errorf("prefix %q: %s not found", prefix, walked)
		}
		cur = deref(next)
		if isNull(cur) {
			return nil, nil
		}
	}
	if cur.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("prefix %q (line %d): must point to a mapping", prefix, cur.Line)
	}
	return cur, nil
}

// ---------- code generation ----------

type gen struct {
	types      map[string]ast.Expr
	counter    int
	useFmt     bool
	useStrconv bool
	useTime    bool
	usedLookup bool
}

// structFields emits assignments for every YAML key in m onto target (a
// pointer to a struct of type st). setVar, if non-empty, is set to true
// whenever any field receives a value.
func (g *gen) structFields(w *bytes.Buffer, st *ast.StructType, m *yaml.Node, target, setVar, path string) error {
	type fieldInfo struct {
		name string
		typ  ast.Expr
	}
	byKey := map[string]fieldInfo{}
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			return fmt.Errorf("yamlconf: %s: embedded fields are not supported", joinPath(path, exprString(f.Type)))
		}
		key := ""
		if f.Tag != nil {
			tag, err := strconv.Unquote(f.Tag.Value)
			if err == nil {
				key, _, _ = strings.Cut(reflect.StructTag(tag).Get("yaml"), ",")
			}
		}
		if key == "-" {
			continue
		}
		for _, n := range f.Names {
			if !n.IsExported() {
				continue
			}
			k := key
			if k == "" {
				k = strings.ToLower(n.Name)
			}
			if _, dup := byKey[k]; dup {
				return fmt.Errorf("yamlconf: %s: duplicate yaml key %q", path, k)
			}
			byKey[k] = fieldInfo{n.Name, f.Type}
		}
	}

	kvs, err := pairs(m, 0)
	if err != nil {
		return fmt.Errorf("yamlconf: %s: %w", orRoot(path), err)
	}
	for _, kv := range kvs {
		key := kv.key.Value
		fpath := joinPath(path, key)
		fi, ok := byKey[key]
		if !ok {
			return fmt.Errorf("yamlconf: %s (line %d): no struct field for this key", fpath, kv.key.Line)
		}
		if err := g.emit(w, fi.typ, kv.val, target+"."+fi.name, setVar, fpath); err != nil {
			return err
		}
	}
	return nil
}

// emit generates code that stores the value described by node into dst,
// whose Go type is typ. setVar is flagged when anything gets stored.
func (g *gen) emit(w *bytes.Buffer, typ ast.Expr, node *yaml.Node, dst, setVar, path string) error {
	node = deref(node)
	if isNull(node) {
		return nil
	}

	// Slices and maps are reference types: accept them directly.
	if c, name := g.container(typ); c != nil {
		return g.emitContainer(w, c, name, node, dst, setVar, path)
	}

	star, ok := typ.(*ast.StarExpr)
	if !ok {
		return fmt.Errorf("yamlconf: %s: type %s must be a pointer, slice or map", path, exprString(typ))
	}

	// *[]T / *map[string]T: build the container, then take its address.
	if c, name := g.container(star.X); c != nil {
		g.counter++
		p := fmt.Sprintf("p%d", g.counter)
		var inner bytes.Buffer
		if err := g.emitContainer(&inner, c, name, node, p, "", path); err != nil {
			return err
		}
		if inner.Len() == 0 {
			return nil
		}
		fmt.Fprintf(w, "\t{\n\tvar %s %s\n", p, typeString(star.X))
		w.Write(inner.Bytes())
		fmt.Fprintf(w, "\tif %s != nil {\n\t%s = &%s\n", p, dst, p)
		markSet(w, setVar)
		w.WriteString("\t}\n\t}\n")
		return nil
	}

	sc, nested, typeName, err := g.resolve(star.X)
	if err != nil {
		return fmt.Errorf("yamlconf: %s: %w", path, err)
	}
	if nested != nil {
		if node.Kind != yaml.MappingNode {
			return fmt.Errorf("yamlconf: %s (line %d): %s is a struct, YAML value must be a mapping", path, node.Line, typeName)
		}
		if typeName == "" {
			return fmt.Errorf("yamlconf: %s: anonymous structs are not supported, use a named type", path)
		}
		return g.nested(w, nested, typeName, node, dst, setVar, path)
	}

	if node.Kind != yaml.ScalarNode {
		return fmt.Errorf("yamlconf: %s (line %d): expected a scalar value for %s", path, node.Line, sc.goType)
	}
	v, err := parseValue(node)
	if err != nil {
		return fmt.Errorf("yamlconf: %s (line %d): %w", path, node.Line, err)
	}
	return g.scalar(w, *sc, v, dst, setVar, path, node.Line)
}

// container reports whether typ is (or names) a slice or map type. The
// returned name is what to pass to make().
func (g *gen) container(typ ast.Expr) (ast.Expr, string) {
	cur := typ
	for depth := 0; depth < 16; depth++ {
		switch t := cur.(type) {
		case *ast.ArrayType:
			if t.Len != nil {
				return nil, "" // fixed arrays unsupported
			}
			return t, typeString(typ)
		case *ast.MapType:
			return t, typeString(typ)
		case *ast.Ident:
			def, ok := g.types[t.Name]
			if !ok {
				return nil, ""
			}
			cur = def
		default:
			return nil, ""
		}
	}
	return nil, ""
}

func (g *gen) emitContainer(w *bytes.Buffer, c ast.Expr, makeType string, node *yaml.Node, dst, parentSet, path string) error {
	g.counter++
	id := g.counter
	set := fmt.Sprintf("set%d", id)
	var inner bytes.Buffer
	var size int

	switch t := c.(type) {
	case *ast.ArrayType:
		if node.Kind != yaml.SequenceNode {
			return fmt.Errorf("yamlconf: %s (line %d): %s needs a YAML sequence", path, node.Line, makeType)
		}
		l := fmt.Sprintf("l%d", id)
		size = len(node.Content)
		for i, item := range node.Content {
			if err := g.emit(&inner, t.Elt, item, fmt.Sprintf("%s[%d]", l, i), set, fmt.Sprintf("%s[%d]", path, i)); err != nil {
				return err
			}
		}
		if inner.Len() == 0 {
			return nil
		}
		fmt.Fprintf(w, "\t{\n\t%s := make(%s, %d)\n\t%s := false\n", l, makeType, size, set)
		w.Write(inner.Bytes())
		fmt.Fprintf(w, "\tif %s {\n\t%s = %s\n", set, dst, l)
	case *ast.MapType:
		if k, ok := t.Key.(*ast.Ident); !ok || k.Name != "string" {
			return fmt.Errorf("yamlconf: %s: only map[string]... is supported, got %s", path, makeType)
		}
		if node.Kind != yaml.MappingNode {
			return fmt.Errorf("yamlconf: %s (line %d): %s needs a YAML mapping", path, node.Line, makeType)
		}
		kvs, err := pairs(node, 0)
		if err != nil {
			return fmt.Errorf("yamlconf: %s: %w", path, err)
		}
		m := fmt.Sprintf("m%d", id)
		size = len(kvs)
		for _, kv := range kvs {
			k := kv.key.Value
			if err := g.emit(&inner, t.Value, kv.val, fmt.Sprintf("%s[%q]", m, k), set, joinPath(path, k)); err != nil {
				return err
			}
		}
		if inner.Len() == 0 {
			return nil
		}
		fmt.Fprintf(w, "\t{\n\t%s := make(%s, %d)\n\t%s := false\n", m, makeType, size, set)
		w.Write(inner.Bytes())
		fmt.Fprintf(w, "\tif %s {\n\t%s = %s\n", set, dst, m)
	}
	markSet(w, parentSet)
	w.WriteString("\t}\n\t}\n")
	return nil
}

type kv struct{ key, val *yaml.Node }

// pairs flattens a mapping node, applying YAML merge keys (`<<: *anchor` or
// `<<: [*a, *b]`). Explicit keys override merged ones; among merged sources
// the earlier one wins, per the YAML merge spec.
func pairs(m *yaml.Node, depth int) ([]kv, error) {
	if depth > 32 {
		return nil, errors.New("merge keys nested too deeply")
	}
	var own, merged []kv
	for i := 0; i+1 < len(m.Content); i += 2 {
		k, v := m.Content[i], m.Content[i+1]
		if k.Tag == "!!merge" || (k.Value == "<<" && k.Style == 0) {
			v = deref(v)
			var srcs []*yaml.Node
			switch v.Kind {
			case yaml.MappingNode:
				srcs = []*yaml.Node{v}
			case yaml.SequenceNode:
				for _, s := range v.Content {
					srcs = append(srcs, deref(s))
				}
			default:
				return nil, fmt.Errorf("line %d: merge key needs a mapping or list of mappings", v.Line)
			}
			for _, s := range srcs {
				if s.Kind != yaml.MappingNode {
					return nil, fmt.Errorf("line %d: merge source must be a mapping", s.Line)
				}
				sub, err := pairs(s, depth+1)
				if err != nil {
					return nil, err
				}
				merged = append(merged, sub...)
			}
			continue
		}
		own = append(own, kv{k, v})
	}
	seen := map[string]bool{}
	for _, p := range own {
		seen[p.key.Value] = true
	}
	out := own
	for _, p := range merged {
		if !seen[p.key.Value] {
			seen[p.key.Value] = true
			out = append(out, p)
		}
	}
	return out, nil
}

func orRoot(path string) string {
	if path == "" {
		return "<root>"
	}
	return path
}

// typeString renders a type expression as Go source.
func typeString(e ast.Expr) string {
	var b bytes.Buffer
	if err := format.Node(&b, token.NewFileSet(), e); err != nil {
		return exprString(e)
	}
	return b.String()
}

func (g *gen) nested(w *bytes.Buffer, st *ast.StructType, typeName string, m *yaml.Node, dst, parentSet, path string) error {
	g.counter++
	n := fmt.Sprintf("n%d", g.counter)
	set := fmt.Sprintf("set%d", g.counter)

	var inner bytes.Buffer
	if err := g.structFields(&inner, st, m, n, set, path); err != nil {
		return err
	}
	if inner.Len() == 0 {
		return nil // nothing can ever be set; field stays nil
	}
	fmt.Fprintf(w, "\t{\n\t\t%s := &%s{}\n\t\t%s := false\n", n, typeName, set)
	w.Write(inner.Bytes())
	fmt.Fprintf(w, "\t\tif %s {\n\t\t\t%s = %s\n", set, dst, n)
	markSet(w, parentSet)
	w.WriteString("\t\t}\n\t}\n")
	return nil
}

func markSet(w *bytes.Buffer, setVar string) {
	if setVar != "" {
		fmt.Fprintf(w, "\t%s = true\n", setVar)
	}
}

func (g *gen) scalar(w *bytes.Buffer, t scalarType, v value, dst, setVar, path string, line int) error {
	var lit string
	if v.hasFallback {
		var err error
		lit, err = g.literal(t, v.fallback)
		if err != nil {
			return fmt.Errorf("yamlconf: %s (line %d): value %q is not a valid %s: %w", path, line, v.fallback, t.goType, err)
		}
	}

	assignLit := func() {
		fmt.Fprintf(w, "\tt := %s\n\t%s = &t\n", lit, dst)
		markSet(w, setVar)
	}

	if v.env == "" {
		if v.hasFallback {
			w.WriteString("\t{\n")
			assignLit()
			w.WriteString("\t}\n")
		}
		return nil
	}

	g.usedLookup = true
	fmt.Fprintf(w, "\tif v, ok := lookup(%q); ok && v != \"\" {\n", v.env)
	g.parseEnv(w, t, path, v.env)
	fmt.Fprintf(w, "\t%s = &t\n", dst)
	markSet(w, setVar)
	if v.hasFallback {
		w.WriteString("\t} else {\n")
		assignLit()
	}
	w.WriteString("\t}\n")
	return nil
}

// parseEnv emits code converting string v into variable t of the field type.
func (g *gen) parseEnv(w *bytes.Buffer, t scalarType, path, env string) {
	var call string
	switch t.kind {
	case kString:
		if t.goType == "string" {
			w.WriteString("\tt := v\n")
		} else {
			fmt.Fprintf(w, "\tt := %s(v)\n", t.goType)
		}
		return
	case kBool:
		g.useStrconv = true
		call = "strconv.ParseBool(v)"
	case kInt:
		g.useStrconv = true
		call = fmt.Sprintf("strconv.ParseInt(v, 10, %d)", t.bits)
	case kUint:
		g.useStrconv = true
		call = fmt.Sprintf("strconv.ParseUint(v, 10, %d)", t.bits)
	case kFloat:
		g.useStrconv = true
		call = fmt.Sprintf("strconv.ParseFloat(v, %d)", t.bits)
	case kDuration:
		g.useTime = true
		call = "time.ParseDuration(v)"
	}
	g.useFmt = true
	msg := strings.ReplaceAll(fmt.Sprintf("yamlconf: %s (env %s): ", path, env), "%", "%%") + "%w"
	fmt.Fprintf(w, "\tx, err := %s\n\tif err != nil {\n\treturn nil, fmt.Errorf(%q, err)\n\t}\n", call, msg)
	fmt.Fprintf(w, "\tt := %s(x)\n", t.goType)
}

// literal validates s against t and returns a Go constant expression.
func (g *gen) literal(t scalarType, s string) (string, error) {
	if strings.Contains(t.goType, "time.") {
		g.useTime = true
	}
	bits := t.bits
	if bits == 0 {
		bits = strconv.IntSize
	}
	switch t.kind {
	case kString:
		return fmt.Sprintf("%s(%s)", t.goType, strconv.Quote(s)), nil
	case kBool:
		b, err := strconv.ParseBool(s)
		if err != nil {
			return "", unwrapNum(err)
		}
		return fmt.Sprintf("%s(%t)", t.goType, b), nil
	case kInt:
		n, err := strconv.ParseInt(s, 10, bits)
		if err != nil {
			return "", unwrapNum(err)
		}
		return fmt.Sprintf("%s(%d)", t.goType, n), nil
	case kUint:
		n, err := strconv.ParseUint(s, 10, bits)
		if err != nil {
			return "", unwrapNum(err)
		}
		return fmt.Sprintf("%s(%d)", t.goType, n), nil
	case kFloat:
		f, err := strconv.ParseFloat(s, bits)
		if err != nil {
			return "", unwrapNum(err)
		}
		if math.IsInf(f, 0) || math.IsNaN(f) {
			return "", errors.New("inf/nan not allowed")
		}
		return fmt.Sprintf("%s(%s)", t.goType, strconv.FormatFloat(f, 'g', -1, bits)), nil
	case kDuration:
		d, err := time.ParseDuration(s)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s(%d)", t.goType, d), nil
	}
	return "", fmt.Errorf("unsupported kind")
}

func unwrapNum(err error) error {
	var ne *strconv.NumError
	if errors.As(err, &ne) {
		return ne.Err
	}
	return err
}

func joinPath(parent, key string) string {
	if parent == "" {
		return key
	}
	return parent + "." + key
}
